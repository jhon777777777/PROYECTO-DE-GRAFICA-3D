import assert from 'node:assert/strict';
import { Matrix4 } from '../js/math/Matrix4.js';
import { Scene } from '../js/core/Scene.js';
import { CubeGeometry } from '../js/geometries/CubeGeometry.js';
import { ConeGeometry } from '../js/geometries/ConeGeometry.js';
import { CylinderGeometry } from '../js/geometries/CylinderGeometry.js';
import { SphereGeometry } from '../js/geometries/SphereGeometry.js';
import { EllipseTrackGeometry } from '../js/geometries/EllipseTrackGeometry.js';
import { PlaneGeometry } from '../js/geometries/PlaneGeometry.js';
import { Train } from '../js/objects/Train.js';
import { RailwayEnvironment } from '../js/objects/RailwayEnvironment.js';
import { HomeroRunner } from '../js/objects/HomeroRunner.js';
import { DayNightCycle } from '../js/systems/DayNightCycle.js';
const g={cubo:new CubeGeometry(),cilindro:new CylinderGeometry(),cono:new ConeGeometry(),esfera:new SphereGeometry(),via:new EllipseTrackGeometry(),rielIzquierdo:new EllipseTrackGeometry(7,4,.045,160,-.21),rielDerecho:new EllipseTrackGeometry(7,4,.045,160,.21),plano:new PlaneGeometry()};
const m={};
for(const name of ['metal','madera','cesped','piedra','balasto','techo','vidrio','follaje','camisa','pantalon','piel','ojos','cabello','zapatos','led','lampOn','lampOff','headlightOn','headlightOff'])m[name]={emissive:['led','lampOn','headlightOn'].includes(name),texture:null};
for(const geom of Object.values(g)){
  assert.equal(geom.vertices.length % 8,0);
  assert.equal(geom.indices.length%3,0);
  assert.ok(Math.max(...geom.indices)<geom.vertices.length/8);
  assert.ok(geom.indexCount>0);
}
const scene=new Scene();
const env=scene.add(new RailwayEnvironment(g,m,7,4));
const train=scene.add(new Train(g,m,7,4));
assert.equal(env.streetLamps.length,8,'Exactamente 8 postes');
assert.equal(env.getEnabledPostCount(),8);
assert.equal(env.streetLamps.filter(lamp=>lamp.position.z>0).length,4);
assert.equal(env.streetLamps.filter(lamp=>lamp.position.z<0).length,4);
assert.ok(env.streetLamps.every(lamp=>lamp.light.enabled));
assert.ok(env.streetLamps.every(lamp=>lamp.bulb.material===m.lampOn));
env.setPostLightEnabled(2,false);
assert.equal(env.getEnabledPostCount(),7);
assert.equal(env.streetLamps[2].bulb.material,m.lampOff);
env.setAllPostLights(false);
assert.equal(env.getEnabledPostCount(),0);
assert.ok(env.streetLamps.every(lamp=>lamp.bulb.material===m.lampOff));
env.setAllPostLights(true);
assert.equal(env.getEnabledPostCount(),7,'Recupera los ajustes individuales');
env.setPostLightEnabled(2,true);
assert.equal(env.getEnabledPostCount(),8);
train.locomotora.setHeadlightEnabled(false);
assert.equal(train.locomotora.faro.enabled,false);
assert.equal(train.locomotora.headlightLens.material,m.headlightOff);
train.locomotora.setHeadlightEnabled(true);
assert.equal(train.locomotora.faro.enabled,true);
assert.equal(train.locomotora.headlightLens.material,m.headlightOn);
const runner=scene.add(new HomeroRunner(g,m));
assert.equal(train.vagones.length,2);
train.setWagonCount(4);
assert.equal(train.vagones.length,4);
train.setTrainSize(1.2);
assert.equal(train.locomotora.scale.x,1.2);
train.update(1);
const ruedasAntes = train.anguloRuedas;
train.velocidadAngular = 0; train.update(1);
assert.equal(train.anguloRuedas, ruedasAntes, "Las ruedas deben detenerse con el tren");
train.velocidadAngular = .45;
assert.ok(Math.abs(train.angulo-.45)<1e-5);
scene.updateMatrixWorld();
assert.ok(Math.abs(train.locomotora.getWorldPosition()[0]-7*Math.cos(train.angulo))<.0001);
assert.ok(train.getProgress()>0);
assert.equal(train.getLaps(),0);
env.setTreeCount(21);env.setBuildingCount(6);
assert.equal(env.trees.length,21);
assert.equal(env.buildings.length,6);
env.setTreeCount(0);env.setBuildingCount(1);
assert.equal(env.trees.length,0);
assert.equal(env.buildings.length,1);
runner.setHairSize(1.8); runner.setSize(1.4); runner.update(.1);
assert.ok(runner.hair.scale.y>1.7);
assert.equal(runner.body.scale.x,1.4);
const projected=Matrix4.ortografica(-10,10,-10,10,1,100);
assert.equal(projected.length,16);
assert.ok(Math.abs(projected[0]-.1)<1e-6);
const renderMock={setSkyColor(c){this.sky=c;}};
const cycle=new DayNightCycle(renderMock);
cycle.setHour(12);
assert.ok(renderMock.sunIntensity>.8);
assert.ok(renderMock.shadowsEnabled);
assert.ok(renderMock.sunDirection[1]>.95);
cycle.setHour(17);
assert.ok(renderMock.sunDirection[1]<.5);
assert.ok(renderMock.sunIntensity>.1);
cycle.setHour(22);
assert.equal(renderMock.sunIntensity,0);
assert.equal(renderMock.shadowsEnabled,false);
assert.ok(renderMock.lampStrength>1);
assert.equal(cycle.getTimeLabel(),'22:00');
cycle.shadowsEnabled=false;cycle.setHour(12);
assert.equal(renderMock.shadowsEnabled,false);
console.log('OK: 8 postes, encendido general/individual, faro, geometrías, tren y ciclo solar');
